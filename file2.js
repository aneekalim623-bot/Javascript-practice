// ==========================
// JavaScript Data Types
// ==========================

// 1. String (Text)
let name = "Anee";
console.log(name);
console.log(typeof name);

// 2. Number
let age = 22;
console.log(age);
console.log(typeof age);

// 3. Boolean
let isStudent = true;
console.log(isStudent);
console.log(typeof isStudent);

// 4. Undefined
let city;
console.log(city);
console.log(typeof city);

// 5. Null
let phone = null;
console.log(phone);
console.log(typeof phone);